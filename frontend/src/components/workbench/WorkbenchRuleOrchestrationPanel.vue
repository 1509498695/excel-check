      ruleForm.expected_value = ''
      ruleForm.reference_variable_tag = ''
      ruleForm.key_check_mode = 'baseline_only'
      resetDualCompositeKeyFields()
      resetCompositeConfig()
      resetDualCompositeComparisons()
      resetDualCompositeFilters()
      resetMappingConfig()
